"""Interface types for the report catalog.

A report type is defined by three things (see catalog.py for the registry):
  - a column catalog: the superset of columns the frontend may pick from
  - a typed params model: the filters that report accepts (extra="forbid")
  - a fetch function: owns all data assembly and returns a ReportPayload

The framework (router/service/renderers/history) depends only on this
interface, so future report types may run multiple queries, aggregate in
Python, or build multi-section payloads without framework changes.
"""

from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field
from typing import Any

from psycopg import AsyncConnection
from pydantic import BaseModel, ConfigDict, Field, model_validator

# Every params field carries an explicit title: it is what the frontend draws
# as the filter's label (it reads params_model.model_json_schema()), and
# Pydantic's generated titles would read "Round Id", "From Round Id", ...


class RoundScopeParams(BaseModel):
    """Filters shared by the v1 flat reports: a round, optionally narrowed
    to one district or one market (market implies its district)."""

    model_config = ConfigDict(extra="forbid")

    round_id: int = Field(title="Round")
    district_id: int | None = Field(default=None, title="District")
    market_id: int | None = Field(default=None, title="Market")

    @model_validator(mode="after")
    def market_requires_district(self):
        if self.market_id is not None and self.district_id is None:
            raise ValueError("market_id requires district_id")
        return self


class MarketSurveyDetailParams(RoundScopeParams):
    """RoundScopeParams plus three optional row narrowings. Each checked flag
    both filters rows and pulls its explaining column into the selection (see
    catalog._detail_columns); multiple flags are OR-combined, so checking
    alerts and DS remark yields rows that have either."""

    only_alerts: bool = Field(default=False, title="Only Price Alerts")
    only_ds_remarks: bool = Field(default=False, title="Only With DS Remark")
    only_pc_remarks: bool = Field(default=False, title="Only With PC Remark")


class RoundRangeParams(BaseModel):
    """Filters for multi-round comparison reports: an inclusive range of
    rounds, optionally narrowed to one district or one market. The range is
    resolved by round_number within the to-round's cycle, not by round_id —
    see service._assert_references for the ordering/cycle/size checks."""

    model_config = ConfigDict(extra="forbid")

    from_round_id: int = Field(title="From Round")
    to_round_id: int = Field(title="To Round")
    district_id: int | None = Field(default=None, title="District")
    market_id: int | None = Field(default=None, title="Market")

    @model_validator(mode="after")
    def market_requires_district(self):
        if self.market_id is not None and self.district_id is None:
            raise ValueError("market_id requires district_id")
        return self


class RoundDistrictParams(BaseModel):
    """Filters for market-level rollup reports: a round, optionally one
    district. No market filter — a single-market rollup is just one row."""

    model_config = ConfigDict(extra="forbid")

    round_id: int = Field(title="Round")
    district_id: int | None = Field(default=None, title="District")


@dataclass(frozen=True)
class Col:
    label: str


@dataclass
class ReportSection:
    """One table in the rendered document. columns is ordered and, after
    projection in the service, contains exactly what gets rendered."""

    columns: dict[str, Col]
    rows: list[dict[str, Any]]
    heading: str | None = None


@dataclass
class ReportPayload:
    """Renderer-agnostic content of one report. meta is label/value pairs
    shown in the document header block (round, district, generated by...)."""

    sections: list[ReportSection]
    meta: list[tuple[str, str]] = field(default_factory=list)


FetchFn = Callable[[AsyncConnection, Any], Awaitable[ReportPayload]]

# (params, chosen columns or None) -> the columns to render. Lets a report
# whose filters imply columns resolve them itself; see service._validate_columns.
ColumnsFn = Callable[[Any, list[str] | None], list[str]]


@dataclass(frozen=True)
class ReportType:
    key: str
    title: str
    description: str
    columns: dict[str, Col]  # selectable superset, in canonical display order
    default_columns: list[str]
    params_model: type[BaseModel]
    fetch: FetchFn
    sequence: int = 0  # 1-based display order in GET /reports/types
    columns_fn: ColumnsFn | None = None  # overrides default_columns when set
    # column key -> param keys that force it into the selection. Published by
    # GET /reports/types so the frontend can lock those columns rather than
    # duplicating the mapping; columns_fn is the server-side half.
    implied_by: dict[str, list[str]] = field(default_factory=dict)
